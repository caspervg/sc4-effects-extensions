"""Command-oriented binding catalog.

Transcribed from `docs/reference/binary/effdir.md` ("Parser cross-reference"
section) per the schema in `docs/reference/binary/effdir-editor-spec.md`
("Command-oriented interpretation"). This is a starter set, not the full
table: see the spec for why a partial catalog is intentional.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Literal, Optional

Role = Literal["parser", "reader", "writer", "consumer"]
Evidence = Literal["wire", "parser", "runtime", "inferred"]
Encoding = Literal[
    "u8", "u16", "u32", "f32", "Vec2", "Vec3",
    "range", "enum", "curve", "resource_key", "string", "raw",
]

EFFDIR_MD = "docs/reference/binary/effdir.md"


@dataclass(frozen=True)
class DocumentRef:
    path: str
    anchor: Optional[str] = None


@dataclass(frozen=True)
class BitRef:
    member_path: str
    bit: int


@dataclass(frozen=True)
class CodeRef:
    address: str
    role: Role


@dataclass(frozen=True)
class Transform:
    description: str
    reversible: bool
    implementation: str


@dataclass(frozen=True)
class CommandBinding:
    id: str
    command_path: str
    syntax_sources: List[DocumentRef]
    record_type: str
    member_paths: List[str]
    presence_bits: List[BitRef]
    encoding: str
    transforms: List[Transform]
    shared_storage_group: Optional[str]
    conflicts: List[str]
    evidence: str
    parser_refs: List[CodeRef]
    runtime_refs: List[CodeRef]
    notes: str


def _doc(anchor: Optional[str] = None) -> List[DocumentRef]:
    return [DocumentRef(path=EFFDIR_MD, anchor=anchor)]


