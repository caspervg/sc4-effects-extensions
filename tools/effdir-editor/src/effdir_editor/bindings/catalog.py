def find_bindings(record_type: str, member_path: str) -> List[CommandBinding]:
    return [
        binding
        for binding in CATALOG
        if binding.record_type == record_type and member_path in binding.member_paths
    ]


def find_by_id(binding_id: str) -> Optional[CommandBinding]:
    for binding in CATALOG:
        if binding.id == binding_id:
            return binding
    return None
